#!/usr/bin/env python3
"""FitJournal design tokens: generate derived outputs + check every codebase for drift.

Source of truth (Multiplatform repo):
  shared/src/commonMain/kotlin/kz/maestrosultan/fitjournal/kmp/design/ColorTokens.kt
  shared/src/commonMain/kotlin/kz/maestrosultan/fitjournal/kmp/design/DesignTokens.kt

  design_tokens.py generate   -> design/tokens.css (Claude Design app/tokens.css), design/TOKENS.md,
                                 design/Design Tokens.dc.html (Claude Design root page),
                                 iOS Colors.xcassets (via iOS/scripts/sync-color-assets.py),
                                 iOS FitJournalWidgets/DesignTokens.generated.swift (the widget
                                 extension links neither FitJournalKMP nor the colour catalog)
  design_tokens.py check      -> scans CMP, native Android and native iOS (Swift + xibs) for literals
                                 that bypass the tokens; exit 1 on any finding.
  design_tokens.py install-hooks  -> pre-commit hook in each repo running `check --repo=<repo>`.
  design_tokens.py check --summary   counts per file only;  --repo=iOS|Android|Multiplatform limits the scan.

Deliberate exceptions live in scripts/design_tokens_allow.txt: `<path glob>:<line regex>  # reason`.
Assumes the sibling layout FitJournal/{Multiplatform,iOS,Android}.
"""
import fnmatch
import pathlib
import re
import subprocess
import sys

MP = pathlib.Path(__file__).resolve().parent.parent
ROOT = MP.parent
DESIGN = MP / "shared/src/commonMain/kotlin/kz/maestrosultan/fitjournal/kmp/design"
OUT = MP / "design"
ALLOW = MP / "scripts/design_tokens_allow.txt"


# ---------------------------------------------------------------- parse
def colors():
    src = (DESIGN / "ColorTokens.kt").read_text()
    return [(n, int(l, 16), int(d, 16)) for n, l, d in
            re.findall(r"val (\w+) = ColorToken\(0x([0-9A-Fa-f]{8}),\s*0x([0-9A-Fa-f]{8})\)", src)]


def scales():
    src = (DESIGN / "DesignTokens.kt").read_text()
    out = {}
    for obj, body in re.findall(r"object (\w+) \{(.*?)\n\}", src, re.S):
        out[obj] = [(n, float(v) if "." in v else int(v))
                    for n, v in re.findall(r"const val (\w+) = (\d+(?:\.\d+)?)", body)]
    return out


def css_color(argb):
    a, rgb = (argb >> 24) & 0xFF, argb & 0xFFFFFF
    return f"#{rgb:06X}" if a == 0xFF else f"rgba({rgb >> 16},{(rgb >> 8) & 0xFF},{rgb & 0xFF},{round(a / 255, 2)})"


# ---------------------------------------------------------------- generate
def generate():
    OUT.mkdir(exist_ok=True)
    c, s = colors(), scales()
    head = "/* GENERATED by Multiplatform/scripts/design_tokens.py from kmp/design/*.kt — do not edit. */\n"
    light = "".join(f"  --{n}:{css_color(l)};\n" for n, l, _ in c)
    dark = "".join(f"  --{n}:{css_color(d)};\n" for n, l, d in c if d != l)
    sizes = "".join(f"  --tracking-{n}:{v}em;\n" if o == "TrackingTokens" else
                    f"  --{'s' if o == 'SpaceTokens' else 'r-' if o == 'RadiusTokens' else ''}{n if o != 'SpaceTokens' else str(v)}:{v}px;\n"
                    for o, vals in s.items() for n, v in vals)
    (OUT / "tokens.css").write_text(head + ".fj{\n" + light + sizes + "}\n.fj[data-theme=\"dark\"]{\n" + dark + "}\n")
    md = ["# FitJournal design tokens", "", "Generated from `Multiplatform/shared/.../kmp/design/` by "
          "`Multiplatform/scripts/design_tokens.py generate`. The app is the source of truth; names are identical "
          "in Kotlin, Swift (via KMP) and the Claude Design CSS (`--<name>`).", "", "## Colour (light / dark)", ""]
    md += [f"- `{n}` {css_color(l)} / {css_color(d)}" for n, l, d in c]
    labels = {"SpaceTokens": "Spacing (CSS `--s<N>`)", "RadiusTokens": "Radius (CSS `--r-<name>`)", "TypeTokens": "Type size (CSS `--<name>`, classes `.t<N>`)",
              "TrackingTokens": "Letter-spacing in em (CSS `--tracking-<name>`)"}
    for o, vals in s.items():
        md += ["", f"## {labels.get(o, o)}", "", ", ".join(f"`{o}.{n}` = {v}" for n, v in vals)]
    (OUT / "TOKENS.md").write_text("\n".join(md) + "\n")
    (OUT / "Design Tokens.dc.html").write_text(token_page(c, s))
    sync = ROOT / "iOS/scripts/sync-color-assets.py"
    if sync.exists():
        subprocess.run([sys.executable, str(sync)], check=True, cwd=ROOT / "iOS")
    widget = ROOT / "iOS/FitJournalWidgets"
    if widget.is_dir():
        (widget / WIDGET_TOKENS).write_text(widget_swift(c, s))
    print(f"wrote {OUT/'tokens.css'}, {OUT/'TOKENS.md'}" + (", iOS Colors.xcassets" if sync.exists() else "")
          + (f", iOS FitJournalWidgets/{WIDGET_TOKENS}" if widget.is_dir() else ""))


WIDGET_TOKENS = "DesignTokens.generated.swift"


def widget_swift(c, s):
    """Token constants for the iOS widget extension, same names as the app's DesignTokens+Swift.swift."""
    def color(argb):
        a, r, g, b = (argb >> 24) & 0xFF, (argb >> 16) & 0xFF, (argb >> 8) & 0xFF, argb & 0xFF
        return f"Color(.sRGB, red: 0x{r:02X} / 255.0, green: 0x{g:02X} / 255.0, blue: 0x{b:02X} / 255.0, opacity: 0x{a:02X} / 255.0)"

    def palette(theme, i):
        rows = "".join(f"        static let {n} = {color(v[i])}\n" for n, *v in c)
        return f"    enum {theme} {{\n{rows}    }}\n"

    def scale(enum, obj):
        rows = "".join(f"    static let {n}: CGFloat = {v}\n" for n, v in s[obj])
        return f"enum {enum} {{\n{rows}}}\n"

    return ("// GENERATED by Multiplatform/scripts/design_tokens.py from kmp/design/*.kt — do not edit.\n"
            "// The widget extension links neither FitJournalKMP nor the app's colour catalog, so the\n"
            "// token values are baked in here. Names match the app's DesignTokens+Swift.swift.\n\n"
            "import SwiftUI\n\n"
            "/// Colour tokens per theme (`ColorTokens.kt` light / dark values).\n"
            "enum TokenColor {\n" + palette("Light", 0) + palette("Dark", 1) + "}\n\n"
            + scale("Space", "SpaceTokens") + "\n" + scale("Radius", "RadiusTokens") + "\n"
            + scale("TypeSize", "TypeTokens") + "\n"
            + "/// Letter-spacing in em; multiply by the font size for kerning points.\n"
            + scale("Tracking", "TrackingTokens"))


