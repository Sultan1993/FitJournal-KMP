# ---------------------------------------------------------------- check
def allow_rules():
    rules = []
    if ALLOW.exists():
        for line in ALLOW.read_text().splitlines():
            line = line.split("  #")[0].strip()
            if line and not line.startswith("#"):
                g, _, rx = line.partition(":")
                rules.append((g.strip(), re.compile(rx.strip() or ".")))
    return rules


def allowed(rules, rel, text):
    return any(fnmatch.fnmatch(rel, g) and r.search(text) for g, r in rules)


N = r"(\d+(?:\.\d+)?)"
KT_RULES = [
    ("colour literal", re.compile(r"\bColor\(0x[0-9A-Fa-f]{6,8}|\bColor\.(?:White|Black)\b")),
    ("type literal", re.compile(r"(?<![\w.])" + N + r"\.sp\b")),
    ("scrim alpha override", re.compile(r"\bscrim\b[^\n]*?\.copy\(\s*alpha")),
    ("legacy colour name", re.compile(r"FitJournalColors\.(?:primary|green|red|Light|Dark|primaryText|gray|darkGray|lightGray|card)\b(?!\w)")),
    ("off-token palette", re.compile(r"\bbrandRamp\b")),
    # named constants that are really tokens: `val CardPadding = 16.dp`, `val SheetCorner: Dp = 28.dp`
    ("named spacing/radius literal", re.compile(r"(?i)\bval \w*(?:Padding|Inset|Gap|Spacing|Margin|Gutter|Radius|Corner)\w*\s*(?::\s*Dp)?\s*=\s*(?!0\b)" + N + r"\.dp\b")),
]
# Call-argument rules use balanced-paren extraction (regexes stop at the first ')').
KT_CALLS = [
    ("radius literal", re.compile(r"RoundedCornerShape\(")),
    ("spacing literal", re.compile(r"\b(?:padding|spacedBy|PaddingValues|contentPadding)\(|Spacer\(\s*(?:modifier\s*=\s*)?Modifier\.(?:height|width|size)\(")),
]
DP = re.compile(r"(?<![\w.])(?!0(?:\.0)?\.dp)" + N + r"\.dp\b")


def call_args(line, start):
    depth, i = 1, start
    while i < len(line) and depth:
        depth += {"(": 1, ")": -1}.get(line[i], 0)
        i += 1
    return line[start:i]


def kt_call_hits(line):
    for kind, rx in KT_CALLS:
        for m in rx.finditer(line):
            if DP.search(call_args(line, m.end())):
                yield kind


SWIFT_RULES = [
    ("colour literal", re.compile(r"(UIColor|Color)\((red|white|hex|displayP3Red):|\.system(Blue|Red|Green|Gray|Yellow|Orange|Purple|Pink|Teal|Indigo)\b|#colorLiteral|hexString:|(?:UIColor|Color)\.(?:white|black|lightGray|darkGray|gray|red|green|blue|orange|yellow|purple)\b|(?:[=(:,]\s*)\.(?:white|black|lightGray|darkGray)\b")),
    ("type literal", re.compile(r"(?:ofSize|size):\s*" + N + r"(?![\w.])")),
    ("scrim alpha override", re.compile(r"\.scrim\b[^\n]*?withAlphaComponent")),
    ("named spacing/radius literal", re.compile(r"\b(?:let|var) \w*(?:[Pp]adding|[Ii]nset|[Gg]ap|[Ss]pacing|[Mm]argin|[Gg]utter|[Rr]adius|[Cc]orner)\w*\s*(?::\s*CGFloat)?\s*=\s*(?!0\b)" + N + r"(?![\w.])")),
    ("radius literal", re.compile(r"cornerRadius(?:\s*=\s*|:\s*|\()\s*(?!0\b)" + N + r"(?![\w.])")),
    ("spacing literal", re.compile(r"(?:\.padding\((?:[^)]*?,\s*)?|spacing:\s*|UIEdgeInsets\([^)]*?:\s*|directionalLayoutMargins[^\n]*?:\s*)(?!0\b)" + N + r"(?![\w.])")),
]
XIB_RULES = [  # IB can't reference code: values must sit ON the scale, colours must be named assets
    ("type off-scale", re.compile(r'<fontDescription [^>]*pointSize="' + N + '"'), "TypeTokens"),
    ("radius off-scale", re.compile(r'keyPath="(?:layer\.)?cornerRadius">\s*<integer value="' + N + '"'), "RadiusTokens"),
    ("spacing off-scale", re.compile(r'<stackView [^>]*spacing="' + N + '"'), "SpaceTokens"),
    ("scrim alpha override", re.compile(r'name="colorScrim"[^>]*alpha=|<view [^>]*alpha="0\.\d+"[^>]*>\s*$'), None),
    ("colour literal", re.compile(r'<color key="[^"]+" (?:red|white)=(?!.*alpha="0(?:\.0)?")|systemColor="(?!clearColor)'), None),
]
SKIP_DIRS = {"build", "DerivedData", ".gradle", "Pods", ".build", "generated", "Generated", "node_modules"}
TOKEN_HOMES = ("kmp/design/", "/ui/theme/", "UIColorExtensions.swift", "ColorExtensions.swift", "DesignTokens+", "DesignTokens.generated.swift")


def files(base, exts):
    if not base.exists():
        return
    for p in base.rglob("*"):
        if p.suffix in exts and not (set(p.parts) & SKIP_DIRS):
            yield p


def check(summary=False, only=None):
    rules, scale = allow_rules(), {o: {v for _, v in vals} for o, vals in scales().items()}
    found = []
    targets = [(MP / "shared/src", {".kt"}, KT_RULES), (ROOT / "Android", {".kt"}, KT_RULES),
               (ROOT / "iOS/FitJournal", {".swift"}, SWIFT_RULES), (ROOT / "iOS/FitJournalWidgets", {".swift"}, SWIFT_RULES),
               (ROOT / "iOS/FitJournal", {".xib", ".storyboard"}, None)]
    for base, exts, kinds in targets:
        if only and base.relative_to(ROOT).parts[0] != only:
            continue
        for p in files(base, exts):
            rel = str(p.relative_to(ROOT))
            if any(h in rel for h in TOKEN_HOMES) or re.search(r"/\w*[Tt]ests?\w*/|Tests?\.(kt|swift)$|Preview", rel):
                continue
            for i, line in enumerate(p.read_text(errors="ignore").splitlines(), 1):
                if kinds is None:
                    for kind, rx, obj in XIB_RULES:
                        for m in rx.finditer(line):
                            if obj and float(m.group(1)) in scale[obj]:
                                continue
                            if obj and float(m.group(1)) == 0:
                                continue
                            if not allowed(rules, rel, line):
                                found.append((rel, i, kind, line.strip()))
                    continue
                if line.lstrip().startswith(("//", "*", "/*", "import ")):
                    continue
                hits = [k for k, rx in kinds if rx.search(line)]
                if kinds is KT_RULES:
                    hits += list(kt_call_hits(line))
                for kind in dict.fromkeys(hits):
                    if not allowed(rules, rel, line):
                        found.append((rel, i, kind, line.strip()))
    # Android window themes can't read KMP: the dialog dim must mirror the scrim token's alpha.
    if not only or only == "Android":
        alpha = round(next(l for n, l, _ in colors() if n == "scrim") >> 24 & 0xFF) / 255
        for t in sorted((ROOT / "Android/app/src/main/res").glob("values*/themes.xml")):
            for m in re.finditer(r'backgroundDimAmount">([\d.]+)<', t.read_text()):
                if abs(float(m.group(1)) - alpha) > 0.005:
                    found.append((str(t.relative_to(ROOT)), 0, "dim != scrim token", f"{m.group(1)} vs {alpha:.2f}"))
    if summary:
        from collections import Counter
        for (f, k), n in sorted(Counter((f, k) for f, _, k, _ in found).items()):
            print(f"{n:4d}  {k:18s} {f}")
    else:
        for f, i, k, t in found:
            print(f"{f}:{i}: {k}: {t[:140]}")
    print(f"\n{len(found)} design-token violation(s)", file=sys.stderr)
    return 1 if found else 0


HOOK = """#!/bin/sh
# Installed by Multiplatform/scripts/design_tokens.py install-hooks — design-token drift guard.
git diff --cached --name-only | grep -qE '\\.(kt|swift|xib|storyboard)$' || exit 0
exec python3 "{script}" check --repo={repo}
"""


def install_hooks():
    for repo in ("Multiplatform", "iOS", "Android"):
        git = ROOT / repo / ".git"
        if not git.is_dir():
            continue
        hook = git / "hooks" / "pre-commit"
        if hook.exists() and "design_tokens.py" not in hook.read_text():
            print(f"skip {hook}: an unrelated pre-commit hook exists")
            continue
        hook.parent.mkdir(exist_ok=True)
        hook.write_text(HOOK.format(script=pathlib.Path(__file__).resolve(), repo=repo))
        hook.chmod(0o755)
        print(f"installed {hook}")


if __name__ == "__main__":
    cmd = sys.argv[1] if len(sys.argv) > 1 else "check"
    if cmd == "generate":
        generate()
    elif cmd == "install-hooks":
        install_hooks()
    elif cmd == "check":
        only = next((a.split("=", 1)[1] for a in sys.argv if a.startswith("--repo=")), None)
        sys.exit(check("--summary" in sys.argv, only))
    else:
        sys.exit(__doc__)
